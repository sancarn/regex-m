let
    A = Support[Assert], E = Support[Throws],
    bad = {"(", ")", "[abc", "[z-a]", "[a-\d]", "\", "\xZ1", "\u123", "\p{L}", "\q", "\01", "a{", "a{,2}", "a{2,1}", "a**", "a*?+", "*a", "^*", "(?=a)+", "(?i)a", "(?R)", "(?(1)a)", "(?<>)", "(?<1a>x)", "(?<x>a)(?<x>b)", "\1", "\k<missing>", "(?<x>a)\k<x", "(?<=a*)b", "(?<=a|bc)d", "a{1000001}", "a}", "a]"},
    rows = List.Transform(bad, (p) => E("reject " & p, () => Regex[Compile](p), "Regex.Syntax")) & {
        A("Validate true", () => Regex[Validate]("a+")[Valid], true),
        A("Validate false", () => Regex[Validate]("a(")[Valid], false),
        A("error offset", () => Regex[Validate]("a(")[Error][Detail][Position], 1),
        E("reject errors in unused alternatives", () => Regex[Test]("a", "a|\9"), "Regex.Syntax"),
        E("validate even beyond input", () => Regex[Match]("a", "(", null, 10), "Regex.Syntax"),
        E("reject errors in unused lookbehind", () => Regex[Test]("a", "a|(?<=b*)c"), "Regex.Syntax"),
        E("unknown options", () => Regex[Compile]("a", [ignoreCase = true]), "Regex.Options"),
        E("invalid flag type", () => Regex[Compile]("a", [IgnoreCase = 1]), "Regex.Options"),
        E("null flag", () => Regex[Compile]("a", [DotAll = null]), "Regex.Options"),
        E("invalid steps", () => Regex[Compile]("a", [MaxSteps = 0]), "Regex.Options"),
        E("NaN limit", () => Regex[Compile]("a", [MaxSteps = #nan]), "Regex.Options"),
        E("infinite limit", () => Regex[Compile]("a", [MaxSteps = #infinity]), "Regex.Options"),
        E("fractional start", () => Regex[Match]("a", "a", null, 0.5), "Regex.Options"),
        E("negative start", () => Regex[Match]("a", "a", null, -1), "Regex.Options"),
        E("compiled options are fixed", () => Regex[Match]("a", Regex[Compile]("a"), [DotAll = true]), "Regex.Argument"),
        E("invalid compiled pattern", () => Regex[Match]("a", []), "Regex.Argument"),
        E("invalid replacement type", () => Regex[Replace]("a", "a", 123), "Regex.Argument"),
        E("invalid callback result", () => Regex[Replace]("a", "a", each 123), "Regex.Replacement"),
        E("unknown replacement number", () => Regex[Replace]("a", "a", "$1"), "Regex.Replacement"),
        E("unknown replacement name", () => Regex[Replace]("a", "a", "${missing}"), "Regex.Replacement"),
        E("unclosed replacement name", () => Regex[Replace]("a", "a", "${x"), "Regex.Replacement"),
        E("pattern limit", () => Regex[Compile]("abcd", [MaxPatternLength = 3]), "Regex.Limit"),
        E("nesting limit", () => Regex[Compile]("((a))", [MaxDepth = 1]), "Regex.Limit"),
        E("program limit", () => Regex[Compile]("abcd", [MaxProgramSize = 3]), "Regex.Limit"),
        E("backtracking instruction limit", () => Regex[Test](Text.Repeat("a", 20) & "!", "^(a+)+$", [MaxSteps = 200]), "Regex.Limit"),
        E("failed search shares instruction budget", () => Regex[Test](Text.Repeat("a", 100), "z", [MaxSteps = 20]), "Regex.Limit"),
        E("global matches share instruction budget", () => Regex[Matches](Text.Repeat("a", 100), "a", [MaxSteps = 20]), "Regex.Limit"),
        E("lookaround shares instruction budget", () => Regex[Test](Text.Repeat("a", 100), "(?=a+$)", [MaxSteps = 20]), "Regex.Limit")
    }
in Table.FromRecords(rows)
